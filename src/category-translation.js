const catalog = new Map()
for (const { category, spanishName } of DEFAULT_VOCABULARY) {
  const names = catalog.get(category) || new Set()
  names.add(spanishName)
  catalog.set(category, names)
}

/** Translate only an exact known category; leave custom categories untouched. */
export function translateCategory(value, language = 'en') {
  const original = String(value ?? '')
  const category = original.trim()
  if (language === 'zh' || !catalog.has(category)) return original
  if (language === 'es') {
    const names = catalog.get(category)
    return (
      spanishGeneric[category] || (names.size === 1 ? [...names][0] : original)
    )
  }
  return english[category] || original
}
